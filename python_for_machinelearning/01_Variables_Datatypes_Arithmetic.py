# Variables, Data Types and Arithmetic
name = "Ravi"
age = 20
marks = 85.5
print(name)
print(age)
print(marks)

# data types
print(type(name))
print(type(age))
print(type(marks))
a = 10
b = 5
print(a + b)
print(a - b)
print(a * b)
print(a / b)
print(a % b)
print(a // b)
print(a ** b)

# changing variable value
x = 10
print(x)
x = 20
print(x)

# type conversion
a = "10"
b = int(a)
print(b)
print(type(b))
a = 10
b = float(a)
print(b)
a = 10
b = str(a)
print(b)
print(type(b))

# boolean
is_student = True
print(is_student)
print(type(is_student))

# simple calculation
length = 10
breadth = 20
area = length * breadth
print("Area =", area)

# average
m1 = 80
m2 = 70
m3 = 90
total = m1 + m2 + m3
average = total / 3
print("Total =", total)
print("Average =", average)